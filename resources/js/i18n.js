// Stored current locale
const initialLocale = (typeof window !== 'undefined' && localStorage.getItem('voice_core_locale')) || 'tr'
export const currentLocale = ref(translations[initialLocale] ? initialLocale : 'tr')

export function setLocale(newLocale) {
  if (translations[newLocale]) {
    currentLocale.value = newLocale
    if (typeof window !== 'undefined') {
      localStorage.setItem('voice_core_locale', newLocale)
    }
  }
}

export function t(path, fallback = '') {
  const parts = path.split('.')
  let cur = translations[currentLocale.value]
  for (const p of parts) {
    if (cur && cur[p] !== undefined) {
      cur = cur[p]
    } else {
      cur = null
      break
    }
  }
  if (cur !== null && typeof cur === 'string') return cur

  // Fallback to Turkish if missing in active language
  let trCur = translations.tr
  for (const p of parts) {
    if (trCur && trCur[p] !== undefined) {
      trCur = trCur[p]
    } else {
      trCur = null
      break
    }
  }
  return trCur !== null ? trCur : (fallback || path)
}

export function useI18n() {
  return {
    locale: currentLocale,
    setLocale,
    t,
    languages: VOICE_LANGUAGES,
    currentLanguage: computed(() => VOICE_LANGUAGES.find(l => l.code === currentLocale.value) || VOICE_LANGUAGES[0])
  }
}
